    #[must_use]
    pub fn from_alpha2(code: &str) -> Option<Self> {
        Self::ALL
            .iter()
            .copied()
            .find(|country| country.alpha2().eq_ignore_ascii_case(code))
    }
    /// Looks up a alpha3 without trimming; alphabetic codes ignore ASCII case.
    /// Numeric codes require exactly three digits.
    #[must_use]
    pub fn from_alpha3(code: &str) -> Option<Self> {
        Self::ALL
            .iter()
            .copied()
            .find(|country| country.alpha3().eq_ignore_ascii_case(code))
    }
    /// Looks up a numeric code without trimming; alphabetic codes ignore ASCII case.
    /// Numeric codes require exactly three digits.
    #[must_use]
    pub fn from_numeric_code(code: &str) -> Option<Self> {
        Self::ALL
            .iter()
            .copied()
            .find(|country| country.numeric_code() == code)
    }
