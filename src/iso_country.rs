impl IsoCountry {
    /// Returns all matching legacy variants, retaining aliases such as Burma/Myanmar.
    #[must_use]
    pub fn legacy_countries(self) -> impl DoubleEndedIterator<Item = super::Country> {
        super::Country::ALL
            .iter()
            .copied()
            .filter(move |country| country.iso_country() == Some(self))
    }
    /// Returns the EU member in the dated membership snapshot, if present.
    #[must_use]
    pub fn eu_member(self) -> Option<super::EU> {
        super::EU::ALL
            .iter()
            .copied()
            .find(|member| member.iso_country() == self)
    }
    /// Returns the 50 US states for the United States, or an empty iterator elsewhere.
    #[must_use]
    pub fn states(self) -> impl DoubleEndedIterator<Item = super::States> {
        super::States::ALL
            .iter()
            .copied()
            .filter(move |state| state.iso_country() == self)
    }
    /// Returns Canadian provinces and territories for Canada, or an empty iterator elsewhere.
    #[must_use]
    pub fn canadian_provinces(self) -> impl DoubleEndedIterator<Item = super::CanadianProvince> {
        super::CanadianProvince::ALL
            .iter()
            .copied()
            .filter(move |province| province.iso_country() == self)
    }
}
